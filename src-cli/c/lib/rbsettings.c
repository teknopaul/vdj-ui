uint16_t tc_crc16_xmodem(const void *data, size_t len)
{
    const unsigned char *p = data;
    uint16_t crc = 0;
    size_t i;
    int b;

    for (i = 0; i < len; i++) {
        crc ^= (uint16_t)(p[i] << 8);
        for (b = 0; b < 8; b++) {
            crc = (crc & 0x8000) ? (uint16_t)((crc << 1) ^ 0x1021) : (uint16_t)(crc << 1);
        }
    }
    return crc;
}

/* 0x00 u32 header length (0x60), header text to 0x60, 0x64 u32 payload length, 0x68 magic, payload, u16 CRC, u16 0.
 * Returns the offset of the CRC, or 0 with a message when the shape is wrong. */
static size_t crc_offset(const uint8_t *b, size_t len, const char **why)
{
    uint32_t payload;
    size_t crc_at;

    if (len < 0x70) {
        *why = "too short";
        return 0;
    }
    if (tc_get_le32(b) != 0x60) {
        *why = "unexpected header length";
        return 0;
    }
    if (tc_get_le32(b + 0x68) != 0x12345678) {
        *why = "bad magic";
        return 0;
    }
    payload = tc_get_le32(b + 0x64);             /* counts the magic and the payload bytes */
    crc_at = len - 4;
    if (0x68 + (size_t)payload != crc_at) {
        *why = "payload length does not match the file size";
        return 0;
    }
    if (b[len - 2] != 0 || b[len - 1] != 0) {
        *why = "missing zero padding";
        return 0;
    }
    return crc_at;
}

int tc_settings_verify(const uint8_t *bytes, size_t len, const char **why)
{
    const char *w = "";
    size_t at = crc_offset(bytes, len, &w);

    if (at == 0) {
        if (why != NULL) {
            *why = w;
        }
        return -1;
    }
    if (tc_get_le16(bytes + at) != tc_crc16_xmodem(bytes + 0x68, at - 0x68)) {
        if (why != NULL) {
            *why = "CRC mismatch";
        }
        return -1;
    }
    return 0;
}

int tc_settings_fix_crc(uint8_t *bytes, size_t len)
{
    const char *w;
    size_t at = crc_offset(bytes, len, &w);

    if (at == 0) {
        return -1;
    }
    tc_set_le16(bytes + at, tc_crc16_xmodem(bytes + 0x68, at - 0x68));
    return 0;
}

int tc_settings_load(const char *path, uint8_t **out, size_t *len, char *err, size_t errsz)
{
    char *data;
    size_t n;
    const char *why = "";

    if (tc_read_file(path, &data, &n) != 0) {
        snprintf(err, errsz, "%s: cannot read", path);
        return -1;
    }
    if (tc_settings_verify((uint8_t *)data, n, &why) != 0) {
        snprintf(err, errsz, "%s: %s", path, why);
        free(data);
        return -1;
    }
    *out = (uint8_t *)data;
    *len = n;
    return 0;
}

